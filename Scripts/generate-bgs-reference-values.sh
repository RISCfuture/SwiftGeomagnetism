#!/usr/bin/env bash
#
# Regenerates Tests/SwiftGeomagnetismTests/Resources/BGS_WMM2025_reference_values.csv from the
# British Geological Survey's geomagnetic model web service, an implementation of the World Magnetic
# Model independent of NOAA's. The points cover what NOAA's published test values do not: the
# geographic poles themselves, calendar dates rather than decimal years, and heights at the edges of
# the model's domain (−1 km and 850 km above the WGS 84 ellipsoid). The service evaluates each
# date at noon UTC.
#
# Usage: Scripts/generate-bgs-reference-values.sh
# Requires curl and jq.

set -euo pipefail

readonly service="https://geomag.bgs.ac.uk/web_service/GMModels/wmm/2025"
readonly output="Tests/SwiftGeomagnetismTests/Resources/BGS_WMM2025_reference_values.csv"
readonly request_interval_seconds=1

# date latitude longitude altitude_km
readonly points="
2025-01-01 90 0 0
2026-06-01 90 120 0
2028-02-29 90 -75 400
2029-12-31 90 0 850
2025-03-15 -90 0 0
2027-08-20 -90 145 0
2029-06-30 -90 -60 850
2026-11-17 89.99 45 0
2027-04-01 -89.99 -30 0
2025-09-09 89.999 170 5
2025-07-02 37.62 -122.38 -1
2026-12-31 51.48 0 -1
2028-02-29 -33.95 151.18 850
2029-12-31 64.13 -21.94 0
2027-01-01 -77.85 166.67 0
2028-07-15 0 -90 120
"

query() {
  local date=$1 latitude=$2 longitude=$3 altitude=$4
  curl --silent --show-error --fail \
    "${service}?latitude=${latitude}&longitude=${longitude}&altitude=${altitude}&date=${date}&format=json"
}

to_csv_row() {
  local date=$1 latitude=$2 longitude=$3 altitude=$4
  jq --raw-output \
    --arg date "$date" --arg latitude "$latitude" --arg longitude "$longitude" --arg altitude "$altitude" \
    '.["geomagnetic-field-model-result"] as $result
      | $result["field-value"] as $field
      | $result["secular-variation"] as $rate
      | [$date, $latitude, $longitude, $altitude,
         $field.declination.value, $field.inclination.value,
         $field["north-intensity"].value, $field["east-intensity"].value,
         $field["vertical-intensity"].value, $field["horizontal-intensity"].value,
         $field["total-intensity"].value,
         $rate.declination.value, $rate.inclination.value,
         $rate["north-intensity"].value, $rate["east-intensity"].value,
         $rate["vertical-intensity"].value, $rate["horizontal-intensity"].value,
         $rate["total-intensity"].value]
      | @csv'
}

{
  echo "# Generated by Scripts/generate-bgs-reference-values.sh from ${service}"
  echo "# Altitude is above the WGS 84 ellipsoid. Angles are in degrees; their rates in arcminutes per year."
  echo "date,latitude,longitude,altitude_km,declination,inclination,north_nT,east_nT,vertical_nT,horizontal_nT,total_nT,declination_rate_arcmin,inclination_rate_arcmin,north_rate_nT,east_rate_nT,vertical_rate_nT,horizontal_rate_nT,total_rate_nT"
  while read -r date latitude longitude altitude; do
    [[ -z $date ]] && continue
    query "$date" "$latitude" "$longitude" "$altitude" | to_csv_row "$date" "$latitude" "$longitude" "$altitude"
    sleep "$request_interval_seconds"
  done <<<"$points"
} >"$output"

echo "Wrote $(($(grep -cv "^#" "$output") - 1)) points to ${output}"
